"""Construct Wanted-format vectors independently; Python zlib, no donor/library execution."""
import json
from pathlib import Path
import zlib
from codec_reference import addon_encode, ls_encode

ROOT = Path(__file__).resolve().parents[1]

def scalar(v):
    if isinstance(v, bool):
        return str(v).lower()
    return str(v)

def stamp(record):
    canonical = '\n'.join([record['kind'], record['id'], record['prev'], scalar(record['t'])]
                          + [k + '=' + scalar(record['data'][k]) for k in sorted(record['data'])])
    record['hash'] = f'{zlib.adler32(canonical.encode()):08x}'
    return record

def encoded(value):
    compressor = zlib.compressobj(7, zlib.DEFLATED, -15)
    return addon_encode(compressor.compress(ls_encode(value)) + compressor.flush()).hex()

def main():
    r = stamp(dict(kind='kill', id='Witness Player:1000001', origin='Witness Player',
                   seq=1000001, prev='0', t=720097,
                   data=dict(killer='Player-1-CD', killerName='Friendly One', killerFaction='Alliance',
                             victim='Player-1-AB', victimName='Enemy One', victimFaction='Horde',
                             deathId='d1', zone='Ashenvale', mapId=100, x=50, y=40, l='1-0-6')))
    deep = {}
    for _ in range(9):
        deep = {'a': deep}
    vectors = dict(record=encoded(dict(v='1.29.2', r=[r])), hash=r['hash'],
                   bomb=encoded({'big': 'x'*65536}), over_depth=encoded(deep))
    # Exact output boundary independently built by the reference serializer.
    size = 65536
    value = {'big': 'x'*size}
    while len(ls_encode(value)) != 65536:
        size += 65536-len(ls_encode(value))
        value = {'big': 'x'*size}
    assert len(ls_encode(value)) == 65536
    vectors['limit'] = encoded(value)
    text = '-- Generated by test/wanted_vectors.py; constructed, not captured.\nreturn {\n'
    text += ''.join('    '+k+'='+json.dumps(v)+',\n' for k,v in vectors.items()) + '}\n'
    (ROOT/'test/fixtures/wanted_vectors.lua').write_text(text)
    print(f'Wanted independent vectors: {len(vectors)}; kill hash {r["hash"]}; limit {len(ls_encode(value))} bytes')

if __name__ == '__main__':
    main()
