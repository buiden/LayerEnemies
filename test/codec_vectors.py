"""Generate independent known answers: python3 test/codec_vectors.py

Python stdlib zlib generates RFC 1951 bytes (wbits=-15); no donor is executed.
Independent format-only serializer encoders and audit data supply the other fixtures.
"""
from pathlib import Path
import argparse
import json
import random
import re
import zlib
from codec_reference import ace_encode, ls_encode, normalize, ace_decode, ls_decode, addon_decode

ROOT = Path(__file__).resolve().parents[1]


def lua_bytes(b):
    return 'hex("' + b.hex() + '")'


def lua_value(v):
    if isinstance(v, (str, bytes)):
        return lua_bytes(v.encode() if isinstance(v, str) else v)
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        v = dict(enumerate(v, 1))
    return '{' + ','.join('[' + lua_value(k) + ']=' + lua_value(x) for k, x in v.items()) + '}'


def capture(pattern, text):
    match = re.search(pattern, text, re.S)
    assert match is not None, pattern
    return match[1]


def audits(folder):
    """Import only published illustrative data, not donor source or executable code."""
    wanted = (folder / 'audit-wanted.md').read_text().split('## 11. Byte-level examples')[1].split('## 12.')[0]
    rows = []
    for section in wanted.split('### Example ')[1:]:
        n = int(section.split(':')[0])
        expected = json.loads(capture(r'```json\n(.*?)\n```', section))
        serial = bytes.fromhex(capture(r'Serialized bytes \(hex\):\s*`([0-9a-f]+)`', section))
        frames = [bytes.fromhex(x) for x in re.findall(r'Wire part \d+[^\n]*\n`([0-9a-f]+)`', section)]
        if n <= 4:
            encoded = frames[0]
        elif n == 10:
            encoded = b''.join(x.split(b':', 2)[2] for x in frames)
        else:
            encoded = frames[0].split(b':', 3)[3]
        assert zlib.decompress(addon_decode(encoded), -15) == serial
        assert ls_decode(serial) == normalize(expected)
        rows.append({'name': 'Wanted example ' + str(n), 'serial': serial.hex(), 'encoded': encoded.hex(), 'expected': expected})
    assert len(rows) == 10
    war = (folder / 'audit-warboard.md').read_text().split('## 11. Byte-level examples')[1]
    serial = capture(r'```text\n(\^1.*?)\n```', war).encode()
    data_section = war.split('### Example 6:')[1].split('### Example 7:')[0]
    frame = bytes.fromhex(capture(r'```text\n([a-f0-9]+)\n```', data_section))
    encoded = frame.split(b'|', 2)[2]
    assert zlib.decompress(addon_decode(encoded), -15) == serial
    expected = {'t': 'SHRD', 'v': 5, 'rs': 'pvp', 'av': '1.6.3', 'senderName': 'Test Scout', 'ttl': 1,
                'd': {'faction': 'Horde', 'guid': 'Player-1-ABC', 'name': 'Test', 'realm': 'Scout',
                      'sentAt': 1794873600000, 'isGroupLeader': False, 'shard': '123', 'zone': 'Azshara', 'mapID': 76}}
    assert ace_decode(serial) == normalize(expected)
    payload = {'source_command': 'python3 test/codec_vectors.py --audit-dir ' + str(folder),
               'note': 'Illustrative audit section 11 vectors, not captured network traffic.',
               'wanted': rows, 'warboard': {'serial': serial.hex(), 'encoded': encoded.hex(), 'expected': expected}}
    (ROOT / 'test/fixtures/codec_audits.json').write_text(json.dumps(payload, indent=2) + '\n')


def generate():
    lines = ['-- Generated by: python3 test/codec_vectors.py',
             '-- Python stdlib zlib.compressobj(level, zlib.DEFLATED, -15).',
             'local function hex(s) return (s:gsub("..",function(x) return string.char(tonumber(x,16)) end)) end',
             'return { deflate={']
    samples = [('empty', b'', 1), ('text4000', b'Enemy One|Durotar|50|40|Horde;abcde' * 1, 125),
               ('64k', bytes(range(256)), 256), ('one', b'x', 1)]
    # Exactly 4000 decoded bytes for the frame-budget workload.
    samples[1] = ('text4000', bytes(range(32, 112)), 50)
    rng = random.Random(2671)
    samples.append(('random4000', bytes(rng.randrange(256) for _ in range(4000)), 1))
    samples.append(('dynamic4000', bytes(rng.randrange(32, 112) for _ in range(4000)), 1))
    for name, pattern, count in samples:
        raw = pattern * count
        for level in (0, 3, 5, 7, 9):
            c = zlib.compressobj(level, zlib.DEFLATED, -15)
            wire = c.compress(raw) + c.flush()
            assert zlib.decompress(wire, -15) == raw
            lines.append('{name="%s-%s",plain=string.rep(%s,%d),wire=%s},' %
                         (name, level, lua_bytes(pattern), count, lua_bytes(wire)))
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    bomb = c.compress(b'A' * 1048576) + c.flush()
    lines += ['}, bomb=' + lua_bytes(bomb) + ',']
    c = zlib.compressobj(9, zlib.DEFLATED, -15, strategy=zlib.Z_FIXED)
    wire = c.compress(b'fixed Huffman! ' * 500) + c.flush()
    lines += ['fixed={plain=string.rep("fixed Huffman! ",500),wire=' + lua_bytes(wire) + '},', 'serializers={']
    samples = [{'k': 'H', 'v': '1.29.2', 'f': 1}, {'bytes': bytes(range(256)), 'numbers': [-4096, 0, 4095, 65536, 4294967296, 1/3]},
               {'false': False, 'true': True, 'nested': [{}, {'s': 'repeated', 'again': 'repeated'}]},
               {'x': [1.5, -1.5, 1e100, 5e-324, 2.2250738585072014e-308]},
               {'s': 'x' * 65536}, {str(i): i for i in range(256)}]
    for v in samples:
        a, b = ace_encode(v), ls_encode(v)
        assert ace_decode(a) == normalize(v) and ls_decode(b) == normalize(v)
        lines += ['{expected=' + lua_value(v) + ',ace=' + lua_bytes(a) + ',ls=' + lua_bytes(b) + '},']
    lines += ['},audit={']
    archive = json.loads((ROOT / 'test/fixtures/codec_audits.json').read_text())
    for v in archive['wanted'] + [dict(archive['warboard'], name='WarBoard SHRD')]:
        codec = 'ace' if v['name'].startswith('WarBoard') else 'ls'
        lines += ['{codec="' + codec + '",name="' + v['name'] + '",serial=' + lua_bytes(bytes.fromhex(v['serial'])) + ',encoded=' + lua_bytes(bytes.fromhex(v['encoded'])) + ',expected=' + lua_value(v['expected']) + '},']
    from codec_deflate_cases import cases
    good, bad = cases()
    lines += ['}, goodDeflate={']
    lines += ['{name="' + name + '",wire=' + lua_bytes(wire) + ',plain=' + lua_bytes(raw) + '},' for name, wire, raw in good]
    lines += ['}, badDeflate={']
    lines += ['{name="' + name + '",wire=' + lua_bytes(wire) + '},' for name, wire in bad]
    lines += ['}}']
    (ROOT / 'test/fixtures/codec_vectors.lua').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--audit-dir', type=Path)
    args = parser.parse_args()
    if args.audit_dir:
        audits(args.audit_dir)
    generate()
